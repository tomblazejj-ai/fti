"""Score overview (every factor on −5…+5, one final number on −10…+10) and a
plain-Czech written summary. Pure rules over the cycle's data — the summary is
assembled from sentences, not generated by an AI model, and the UI says so.
"""

from __future__ import annotations

import datetime as dt

PILLARS = [  # model pillar -> label in the score grid
    ("fed", "Fed a sazby"), ("inflation", "Inflace"), ("real_yields", "Reálné výnosy"), ("usd", "Dolar"),
    ("economy", "Ekonomika USA"), ("geopolitics", "Geopolitika"), ("central_banks", "Centrální banky"),
]


def _clip5(x: float) -> int:
    return int(max(-5, min(5, round(x * 5))))


def build_scorecard(pillar_breakdown: dict | None, verdict: dict, technical: dict | None, mtf: dict | None,
                    cot: dict | None, news: dict | None, seasonality: dict | None, dollar: dict | None = None) -> dict:
    items = []
    for key, label in PILLARS:
        p = (pillar_breakdown or {}).get(key)
        if not p or p.get("data_quality") == "unavailable":
            items.append({"key": key, "label": label, "score": None, "group": "fundament"})
            continue
        items.append({"key": key, "label": label, "score": _clip5(p.get("raw_signal", 0.0)), "group": "fundament"})
    items.append({"key": "dxy", "label": "Dolar (DXY)", "score": _clip5(dollar["effect_on_gold"]) if dollar else None, "group": "trhy"})
    items.append({"key": "cot", "label": "COT – fondy", "score": _clip5(cot["signal"]) if cot else None, "group": "pozice"})
    items.append({"key": "trend", "label": "Trend (všechny TF)",
                  "score": _clip5((mtf or {}).get("overall", {}).get("score", 0.0)) if mtf and mtf.get("overall") else None,
                  "group": "technika"})
    items.append({"key": "tech", "label": "Technické ukazatele",
                  "score": _clip5(technical["tech_score"] / 100) if technical else None, "group": "technika"})
    items.append({"key": "news", "label": "Zprávy",
                  "score": _clip5(news["score"]) if news and news.get("score") is not None and news.get("count", 0) >= 3 else None,
                  "group": "sentiment"})
    items.append({"key": "seasonality", "label": "Sezónnost",
                  "score": _clip5(seasonality["signal"]) if seasonality else None, "group": "sentiment"})
    final = int(max(-10, min(10, round(verdict.get("combined", 0.0) * 10))))
    label = ("Silně medvědí" if final <= -6 else "Medvědí" if final <= -2 else "Neutrální" if final < 2
             else "Býčí" if final < 6 else "Silně býčí")
    return {"items": items, "final": final, "final_label": label,
            "note": "Každý faktor −5 (silně pro pokles zlata) až +5 (silně pro růst). Celkové skóre −10 až +10 = vážený souhrn verdiktu."}


def _usd(v: float | None) -> str:
    return "—" if v is None else f"{v:,.2f}".replace(",", " ").replace(".", ",") + " $"


def build_summary(verdict: dict, technical: dict | None, mtf: dict | None, calendar: dict | None,
                  cot: dict | None, decision: dict | None, now: dt.datetime, dollar: dict | None = None) -> dict:
    price = (mtf or {}).get("price")
    day = ((technical or {}).get("changes") or {}).get("1d")
    swing, intraday = (mtf or {}).get("swing"), (mtf or {}).get("intraday")
    lv = (decision or {}).get("levels", {})
    up, down = lv.get("up"), lv.get("down")

    trend_bits = []
    if swing:
        trend_bits.append(f"swingový trend je {swing['word'].lower()}")
    if intraday:
        trend_bits.append(f"intradenně {intraday['word'].lower()}")
    lead = f"{verdict.get('direction_text', 'Zlato')}. " + (f"Cena {_usd(price)}" if price else "")
    if day is not None:
        lead += f" ({day:+.2f} % za den)".replace(".", ",").replace("-", "−")
    if trend_bits:
        lead += ", " + " a ".join(trend_bits)
    lead += "."
    if up and down and up.get("price") and down.get("price"):
        lead += (f" Průraz nad {_usd(up['price'])} by otevřel cestu výš, pád pod {_usd(down['price'])} by potvrdil další pokles.")
    nxt = (calendar or {}).get("next_high")
    if nxt:
        d = dt.date.fromisoformat(nxt["date"])
        lead += f" Sleduj {nxt['name']} ({d.day}. {d.month}.{' v ' + nxt['time'] if nxt.get('time') else ''})."

    bullets = []
    if price:
        bullets.append(f"Aktuální cena: {_usd(price)}")
    if day is not None:
        bullets.append(f"Denní změna: {day:+.2f} %".replace(".", ",").replace("-", "−"))
    tech = []
    if technical:
        tech.append(f"Denní trend: {technical['trend_label'].lower()}, RSI {technical['rsi14']:.0f}".replace(".", ",") if technical.get("rsi14") is not None
                    else f"Denní trend: {technical['trend_label'].lower()}")
    if up and up.get("price"):
        tech.append(f"Nejbližší odpor {_usd(up['price'])} ({up['label'].lower()})")
    if down and down.get("price"):
        tech.append(f"Nejbližší podpora {_usd(down['price'])} ({down['label'].lower()})")
    if cot:
        g = (cot.get("groups") or [{}])[0]
        if g.get("change_1w") is not None:
            tech.append(f"Hedgeové fondy za týden {'přikoupily' if g['change_1w'] > 0 else 'prodaly'} {abs(g['change_1w']):,.0f} kontraktů".replace(",", " "))
    if dollar and dollar.get("price"):
        swing = (dollar.get("trends") or {}).get("swing")
        corr = ((dollar.get("correlation") or {}).get("d60") or {}).get("value")
        tech.append(f"DXY {dollar['price']:.2f}".replace(".", ",") + (f", swingově {swing['word'].lower()}" if swing else "")
                    + (f", korelace se zlatem {corr:+.2f}".replace(".", ",").replace("-", "−") if corr is not None else ""))
    return {"date": now.date().isoformat(), "text": lead, "bullets": bullets, "outlook": tech,
            "note": "Automaticky složeno z dat aplikace podle pevných pravidel — není to AI ani investiční doporučení."}
